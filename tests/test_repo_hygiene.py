from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def lines(name: str) -> set[str]:
    return {line.strip() for line in (ROOT / name).read_text(encoding="utf-8").splitlines()}


def test_secrets_and_backups_are_never_committed() -> None:
    ignored = lines(".gitignore")
    assert {".env", "backups/"} <= ignored


def test_secrets_and_vcs_data_are_kept_out_of_the_image() -> None:
    excluded = lines(".dockerignore")
    assert {".env", ".git", "backups"} <= excluded
    for needed in ("README.md", "LICENSE", "pyproject.toml", "uv.lock", "alembic.ini", "src"):
        assert needed not in excluded  # the build needs them


def test_env_example_contains_no_real_secret() -> None:
    values = {
        key: value
        for key, _, value in (
            line.partition("=")
            for line in lines(".env.example")
            if line and not line.startswith("#")
        )
    }
    assert values["JWT_SECRET"] == ""  # must be generated by whoever deploys
    assert values.get("POSTGRES_PASSWORD", "scitracker") == "scitracker"  # dev default only
